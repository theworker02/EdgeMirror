#!/usr/bin/env node
/**
 * Create EdgeMirror Cloud subscription Products + Prices in Stripe.
 *
 * Prefer TEST mode: STRIPE_SECRET_KEY=sk_test_...
 * Writes .env.stripe.local with price IDs (gitignored) — never commit secrets.
 *
 * Usage:
 *   set STRIPE_SECRET_KEY=sk_test_...
 *   node scripts/stripe-setup-catalog.mjs
 */

import { writeFileSync, appendFileSync, existsSync, readFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

const PLANS = [
  {
    id: "developer",
    name: "EdgeMirror Cloud Developer",
    description:
      "Managed Supercharger, history, private projects. Includes 500 CU/month (Compute Units = entitlements, not currency).",
    amount: 1900,
    env: "STRIPE_PRICE_DEVELOPER",
    metadata: { edgemirror_plan: "developer", monthly_cu: "500" },
  },
  {
    id: "pro",
    name: "EdgeMirror Cloud Pro",
    description:
      "Extended compat matrices, scheduled verify. Includes 2500 CU/month.",
    amount: 4900,
    env: "STRIPE_PRICE_PRO",
    metadata: { edgemirror_plan: "pro", monthly_cu: "2500" },
  },
  {
    id: "team",
    name: "EdgeMirror Cloud Team",
    description: "Org seats and shared findings. Includes 10000 CU/month.",
    amount: 14900,
    env: "STRIPE_PRICE_TEAM",
    metadata: { edgemirror_plan: "team", monthly_cu: "10000" },
  },
];

async function stripe(path, body, key) {
  const res = await fetch(`https://api.stripe.com/v1${path}`, {
    method: "POST",
    headers: {
      Authorization: `Bearer ${key}`,
      "Content-Type": "application/x-www-form-urlencoded",
    },
    body: new URLSearchParams(body),
  });
  const json = await res.json();
  if (!res.ok) {
    throw new Error(JSON.stringify(json, null, 2));
  }
  return json;
}

async function main() {
  const key = process.env.STRIPE_SECRET_KEY?.trim();
  if (!key) {
    console.error("STRIPE_SECRET_KEY is required (prefer sk_test_… for test mode).");
    process.exitCode = 2;
    return;
  }
  if (key.startsWith("sk_live_")) {
    console.warn(
      "WARNING: Using LIVE secret key. Prefer sk_test_ for catalog setup.",
    );
  } else if (!key.startsWith("sk_test_")) {
    console.warn("Key does not look like sk_test_ or sk_live_ — proceeding carefully.");
  }

  const lines = [
    `# Generated by scripts/stripe-setup-catalog.mjs — do not commit secrets`,
    `# Mode: ${key.startsWith("sk_test_") ? "TEST" : key.startsWith("sk_live_") ? "LIVE" : "UNKNOWN"}`,
    `STRIPE_SECRET_KEY=${key}`,
  ];

  for (const plan of PLANS) {
    console.log(`Creating product: ${plan.name}`);
    const product = await stripe(
      "/products",
      {
        name: plan.name,
        description: plan.description,
        "metadata[edgemirror_plan]": plan.metadata.edgemirror_plan,
        "metadata[monthly_cu]": plan.metadata.monthly_cu,
      },
      key,
    );
    console.log(`  product ${product.id}`);
    const price = await stripe(
      "/prices",
      {
        product: product.id,
        unit_amount: String(plan.amount),
        currency: "usd",
        "recurring[interval]": "month",
        "metadata[edgemirror_plan]": plan.metadata.edgemirror_plan,
      },
      key,
    );
    console.log(`  price   ${price.id}  ($${(plan.amount / 100).toFixed(2)}/mo)`);
    lines.push(`${plan.env}=${price.id}`);
  }

  const out = join(ROOT, ".env.stripe.local");
  writeFileSync(out, lines.join("\n") + "\n", "utf8");
  console.log(`\nWrote ${out}`);
  console.log("Load into shell before running API Checkout, e.g.:");
  console.log("  Get-Content .env.stripe.local | ForEach-Object { if ($_ -match '^([^#=]+)=(.*)$') { Set-Item env:$($matches[1]) $matches[2] } }");
}

main().catch((err) => {
  console.error(err instanceof Error ? err.message : err);
  process.exitCode = 1;
});
